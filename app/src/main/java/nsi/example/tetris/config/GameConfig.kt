package nsi.example.tetris.config

import android.graphics.Color

/**
 * Централизованное хранилище всех настроек игры (Single Source of Truth).
 * <p>
 * Содержит цвета, скорости и параметры отрисовки. Вынесение этих данных в отдельный объект
 * позволяет легко менять визуальный стиль и баланс, не затрагивая бизнес-логику.
 */
object GameConfig {
    // --- Скорости игры (в наносекундах) ---
    /** Базовая задержка между тиками (падениями) фигуры на 1 уровне. */
    const val BASE_SPEED = 1_600_000_000L

    /**
     * Множитель скорости за каждый новый уровень.
     * 0.85 = -15% времени на тик (экспоненциальная кривая, как в Tetris Guideline).
     */
    const val SPEED_FACTOR = 0.85

    /** Минимально возможная задержка (предел скорости). */
    const val MIN_SPEED = 100_000_000L

    // --- Цвета фигур ---
    /**
     * Палитра цветов для 7 фигур тетромино.
     * Индекс в массиве соответствует ID цвета фигуры (от 1 до 7). Нулевой индекс пуст.
     */
    val pieceColors = intArrayOf(
        0, // 0 - пусто
        Color.rgb(249, 217, 130), // O
        Color.rgb(126, 200, 200), // I
        Color.rgb(175, 163, 198), // T
        Color.rgb(155, 196, 166), // S
        Color.rgb(240, 168, 145), // Z
        Color.rgb(124, 153, 184), // J
        Color.rgb(200, 207, 214)  // L
    )

    // --- Цвета фона (градиент) ---
    /**
     * Цвета для создания вертикального градиента фона (от неба до гальки).
     */
    val bgColors = intArrayOf(
        Color.parseColor("#4A7C9D"), // Верх: голубое небо
        Color.parseColor("#7FA8C9"), // 35%: светлые облака
        Color.parseColor("#F0B48A"), // 55%: золотой закат
        Color.parseColor("#486880"), // 75%: темная вода
        Color.parseColor("#1D262E")  // Низ: галька
    )

    // --- Позиции для градиента ---
    /**
     * Пропорциональное расположение цветов из [bgColors] по высоте экрана.
     */
    val bgPositions = floatArrayOf(0f, 0.4f, 0.6f, 0.8f, 1f)
}
